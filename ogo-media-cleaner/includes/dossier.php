    private static function key($info) {
        if (!$info || !is_array($info['parts'])) return null;
        $parts=$info['parts'];
        $path=$parts['path']??'';
        if (!isset($parts['host'])) {
            if (preg_match('~^/dossier(?:/|$)~i',$path)!==1) return null;
        } else {
            $host=strtolower($parts['host']);
            if (!in_array($host,array('ogo.ua','www.ogo.ua','ogo.rv.ua','www.ogo.rv.ua'),true)) return null;
            if (!isset($parts['scheme']) || !in_array(strtolower($parts['scheme']),array('http','https'),true)) return null;
            if (preg_match('~^/dossier(?:/|$)~i',$path)!==1) return null;
        }
        $path=strtolower(rawurldecode(rtrim($path,'/')));
        return $path==='/dossier'?null:$path;
    }

    public static function analyze($content,$masked) {
        preg_match_all('~<a\b(?:[^>"\']|"[^"]*"|\'[^\']*\')*>~i',$masked,$tags,PREG_OFFSET_CAPTURE);
        $map=self::map();$after=$content;$total=0;$changed=0;$review=0;$missing=array();$fragments=array();
        foreach(array_reverse($tags[0]) as $tag) {
            $original=substr($content,$tag[1],strlen($tag[0]));
            $info=OGO_MC_Engine::href_info($original);
            $key=self::key($info);
            if ($key===null) continue;
            ++$total;
            if (!isset($map[$key])) {
                ++$review;
                if (count($missing)<12) $missing[]=$key;
                continue;
            }
            $after=substr_replace($after,$map[$key],$tag[1]+$info['offset'],$info['length']);
            ++$changed;
            $fragments[]=$original;
        }
        $summary='';
        if ($missing) $summary='Немає відповідника на Рівнянах для: '.implode(', ',array_unique($missing)).'. Перевірте вручну.';
        return array('after'=>$after,'total'=>$total,'removed'=>$changed,'review'=>$review,'fragments'=>$fragments,'summary'=>$summary);
    }
